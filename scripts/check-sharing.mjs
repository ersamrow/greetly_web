import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const output=ts.transpileModule(fs.readFileSync('lib/share-greeting.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {shareGreeting,greetingShareText}=await import('data:text/javascript;base64,'+Buffer.from(output).toString('base64'));
const url='https://greetly.myledgerpro.in/g/example',file=new File(['test'],'greeting.png',{type:'image/png'});
const sent=[];
await shareGreeting({share:async data=>sent.push(data),canShare:()=>true},url,file);
assert.equal(sent[0].files[0],file);
assert(sent[0].text.includes(url));
assert(sent[0].text.includes('https://greetly.myledgerpro.in/'));
const links=[];
await shareGreeting({share:async data=>links.push(data),canShare:()=>false},url,file);
assert.equal(links[0].url,url);assert(!links[0].files);
let copied='';
assert.equal(await shareGreeting({clipboard:{writeText:async text=>{copied=text}}},url),'copied');
assert.equal(copied,greetingShareText(url));
let calls=0;
await assert.rejects(shareGreeting({canShare:()=>true,share:async()=>{calls++;throw new DOMException('Cancelled','AbortError')}},url,file),{name:'AbortError'});
assert.equal(calls,1,'Cancelling must not reopen the share sheet');
const fallback=[];
await shareGreeting({canShare:()=>true,share:async data=>{fallback.push(data);if(data.files)throw new TypeError('Unsupported files')}},url,file);
assert.equal(fallback[1].url,url);
await assert.rejects(shareGreeting({},url),/Copy the share message/);
console.log('Sharing checks passed: image caption, link-only share, clipboard fallback, cancellation, and unsupported files.');
